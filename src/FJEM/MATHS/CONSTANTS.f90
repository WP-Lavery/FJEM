MODULE FJEM_MATHS_CONSTANTS
  USE FJEM_CORE
  IMPLICIT NONE
  PRIVATE
  PUBLIC pi_, e_

  INTEGER, PARAMETER :: FJEMP = FJEM_PRECISION
  REAL(KIND=FJEM_PRECISION), PARAMETER :: pi_ = 4.0_FJEMP * ATAN(1.0_FJEMP)
  REAL(KIND=FJEM_PRECISION), PARAMETER :: e_ = EXP(1.0_FJEMP)
END MODULE FJEM_MATHS_CONSTANTS
